#!/usr/bin/env python3
"""Render a plain-text terminal transcript as a static SVG (no dependencies).

Lines starting with "$ " are drawn as commands; all other lines as output.
Long lines are wrapped at WIDTH columns so nothing is clipped.
"""
import sys
import textwrap
from xml.sax.saxutils import escape

WIDTH = 78          # monospace columns before wrapping
CHAR_W = 8.4        # px per column at font-size 14
LINE_H = 20
PAD_X, PAD_TOP = 24, 64


def main(src, dst):
    rows = []  # (kind, text)
    for raw in open(src, encoding="utf-8").read().splitlines():
        kind = "cmd" if raw.startswith("$ ") else "out"
        prefix = "" if kind == "cmd" else "  "
        wrapped = textwrap.wrap(raw, WIDTH - len(prefix), subsequent_indent="    ",
                                replace_whitespace=False, drop_whitespace=False) or [""]
        for i, part in enumerate(wrapped):
            rows.append((kind if i == 0 else ("cmd" if kind == "cmd" else "out"), prefix + part))

    width = int(PAD_X * 2 + WIDTH * CHAR_W)
    height = PAD_TOP + len(rows) * LINE_H + 52
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" aria-labelledby="t d">',
        '<title id="t">Captured git-panic session in a disposable practice repository</title>',
        '<desc id="d">Real output from git-panic: search the reflog for a commit lost to '
        'git reset --hard, preview preserving it on a new branch, create the branch, '
        'then show that the branch holds the first version while the working file is unchanged.</desc>',
        f'<rect width="{width}" height="{height}" rx="12" fill="#0d1117"/>',
        f'<rect x="1" y="1" width="{width-2}" height="{height-2}" rx="11" fill="none" stroke="#30363d" stroke-width="2"/>',
        f'<rect x="1" y="1" width="{width-2}" height="40" rx="11" fill="#161b22"/>',
        '<circle cx="24" cy="21" r="6" fill="#ff5f56"/><circle cx="44" cy="21" r="6" fill="#ffbd2e"/>'
        '<circle cx="64" cy="21" r="6" fill="#27c93f"/>',
        f'<text x="{width/2}" y="26" text-anchor="middle" font-family="monospace" font-size="13" fill="#c9d1d9">'
        'captured output / disposable practice repository</text>',
    ]
    y = PAD_TOP
    for kind, text in rows:
        color = "#79c0ff" if kind == "cmd" else "#e6edf3"
        out.append(
            f'<text x="{PAD_X}" y="{y}" xml:space="preserve" font-family="DejaVu Sans Mono, Menlo, Consolas, monospace" '
            f'font-size="14" fill="{color}">{escape(text)}</text>'
        )
        y += LINE_H
    out.append(
        f'<text x="{PAD_X}" y="{height-18}" font-family="system-ui, sans-serif" font-size="12" fill="#a8b3c0">'
        'Generated by scripts/render-demo.sh from the real binary. The first line of each block is the command run.</text>'
    )
    out.append("</svg>")
    open(dst, "w", encoding="utf-8").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
